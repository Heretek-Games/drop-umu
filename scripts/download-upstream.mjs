#!/usr/bin/env node
import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const binDir = path.join(rootDir, "bin");
const srcDir = path.join(rootDir, "src");

async function main() {
  console.log("Fetching latest release information from GitHub...");
  const headers = {
    "User-Agent": "Heretek-Drop-UMU-Fetcher",
    Accept: "application/vnd.github.v3+json",
  };

  const tag = process.argv[2];
  const url = tag
    ? `https://api.github.com/repos/Open-Wine-Components/umu-launcher/releases/tags/${tag}`
    : "https://api.github.com/repos/Open-Wine-Components/umu-launcher/releases/latest";

  const res = await fetch(url, { headers });
  if (!res.ok) {
    throw new Error(`Failed to fetch release info: ${res.status} ${res.statusText}`);
  }

  const release = await res.json();
  const version = release.tag_name;
  console.log(`Found release: ${version}`);

  const asset = release.assets?.find((a) =>
    a.name.startsWith("umu-launcher-") && a.name.endsWith("-zipapp.tar"),
  );

  if (!asset) {
    throw new Error(`Could not find zipapp asset in release ${version}`);
  }

  console.log(`Downloading zipapp asset: ${asset.name} (${asset.size} bytes)...`);
  mkdirSync(binDir, { recursive: true });
  mkdirSync(srcDir, { recursive: true });

  const downloadCmd = `curl -sL "${asset.browser_download_url}" | tar -x -C "${binDir}" --strip-components=1 umu/umu-run`;
  execSync(downloadCmd, { stdio: "inherit" });

  const binPath = path.join(binDir, "umu-run");
  if (!existsSync(binPath)) {
    throw new Error(`Downloaded file not found at ${binPath}`);
  }

  execSync(`chmod +x "${binPath}"`);
  console.log(`Successfully extracted executable to ${binPath}`);

  const bytes = readFileSync(binPath);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const base64 = bytes.toString("base64");

  console.log(`Binary SHA-256: ${sha256} (${bytes.length} bytes)`);

  const embeddedTs = `// Auto-generated by scripts/download-upstream.mjs. Do not edit manually.
export const UMU_RUN_VERSION = ${JSON.stringify(version)};
export const UMU_RUN_SHA256 = ${JSON.stringify(sha256)};
export const UMU_RUN_SIZE = ${bytes.length};
export const UMU_RUN_BASE64 = ${JSON.stringify(base64)};
`;

  writeFileSync(path.join(srcDir, "embedded-umu.ts"), embeddedTs, "utf-8");
  console.log(`Wrote src/embedded-umu.ts`);
}

main().catch((err) => {
  console.error("Error updating upstream UMU:", err);
  process.exit(1);
});
